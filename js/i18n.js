class I18nManager {
    constructor() {
        // More robust language detection
        let savedLang = localStorage.getItem('app_lang');
        if (savedLang && typeof savedLang === 'string') {
            savedLang = savedLang.toLowerCase();
            this.currentLang = translations[savedLang] ? savedLang : 'en';
        } else {
            this.currentLang = 'en';
        }

        console.log(`I18n: Constructor initialized with language: "${this.currentLang}"`);

        // Apply language to HTML tag immediately
        document.documentElement.lang = this.currentLang;

        // Start observation immediately for any early-rendered elements
        this.setupMutationObserver();

        if (document.readyState === 'loading') {
            document.addEventListener('DOMContentLoaded', () => this.init());
        } else {
            this.init();
        }
    }

    setupMutationObserver() {
        // Mutation Observer to handle dynamic content automatically
        this.observer = new MutationObserver((mutations) => {
            mutations.forEach((mutation) => {
                mutation.addedNodes.forEach((node) => {
                    if (node.nodeType === 1) { // Element node
                        // Check the node itself
                        if (node.hasAttribute('data-i18n')) {
                            this.translateElement(node);
                        }
                        // Check all children
                        node.querySelectorAll('[data-i18n]').forEach(el => this.translateElement(el));
                    }
                });
            });
        });

        this.observer.observe(document.body || document.documentElement, {
            childList: true,
            subtree: true
        });
    }

    init() {
        this.updateUI();
        this.attachEventListeners();
    }

    async setLanguage(lang) {
        if (!translations[lang]) return;
        this.currentLang = lang;
        localStorage.setItem('app_lang', lang);

        // Set cookie for server-side access
        document.cookie = `app_lang=${lang}; path=/; max-age=31536000; SameSite=Lax`;

        // Update HTML lang attribute
        document.documentElement.lang = lang;

        this.updateUI();

        // Sync to server session
        try {
            await fetch('/api/set_lang.php', {
                method: 'POST',
                headers: { 'Content-Type': 'application/json' },
                body: JSON.stringify({ lang: lang })
            }).catch(() => {
                // If the path is different (e.g. from student/ subfolder)
                return fetch('../api/set_lang.php', {
                    method: 'POST',
                    headers: { 'Content-Type': 'application/json' },
                    body: JSON.stringify({ lang: lang })
                });
            });
        } catch (e) {
            console.warn("I18n: Failed to sync language to server session", e);
        }
    }

    updateUI() {
        if (!translations[this.currentLang]) {
            console.error(`I18n: Language "${this.currentLang}" not found in translations dictionary.`);
            return;
        }

        console.log(`I18n: Manually triggering UI update to language "${this.currentLang}"`);

        // Update all elements with data-i18n attribute
        document.querySelectorAll('[data-i18n]').forEach(el => this.translateElement(el));

        // Specialized: Handle any alerts or dynamic messages that might be visible
        const langData = translations[this.currentLang];
        document.querySelectorAll('.alert, .toast-body').forEach(el => {
            const currentText = el.innerText.trim();
            // If the text matches a key in our English dict, it's a translatable string
            if (translations['en'][currentText]) {
                el.innerText = this.get(currentText);
                el.setAttribute('data-i18n', currentText);
            }
        });

        const switcher = document.getElementById('langSwitcher');
        if (switcher) switcher.value = this.currentLang;

        window.dispatchEvent(new CustomEvent('languageChanged', { detail: this.currentLang }));
    }

    translateElement(el) {
        const key = el.getAttribute('data-i18n');
        const langData = translations[this.currentLang];
        if (!langData || !key) return;

        const translation = this.get(key);
        if (translation === key && this.currentLang !== 'en') {
            // No translation found and not English - skip
            return;
        }

        if (el.tagName === 'INPUT' && ['text', 'email', 'password', 'search'].includes(el.type)) {
            el.placeholder = translation;
        } else if (el.tagName === 'TEXTAREA') {
            el.placeholder = translation;
        } else if (el.tagName === 'OPTGROUP') {
            el.label = translation;
        } else {
            el.innerText = translation;
        }
    }

    attachEventListeners() {
        document.addEventListener('change', (e) => {
            if (e.target.id === 'langSwitcher') {
                console.log(`I18n: Language switcher changed to "${e.target.value}"`);
                this.setLanguage(e.target.value);
            }
        });
    }

    get(key) {
        if (!key) return '';
        if (!translations[this.currentLang]) return key;

        // Try exact match first
        let res = translations[this.currentLang][key];

        // Try case-insensitive match if not found
        if (!res) {
            const lowerKey = key.toLowerCase();
            const foundKey = Object.keys(translations[this.currentLang]).find(k => k.toLowerCase() === lowerKey);
            if (foundKey) res = translations[this.currentLang][foundKey];
        }

        return res || key;
    }
}

window.i18n = new I18nManager();
